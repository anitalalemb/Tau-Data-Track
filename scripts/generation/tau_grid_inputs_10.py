def make_poscar_text(short, coords):
    elem_order = ["Sr", "Ti", "O"]
    grouped = [atom for el in elem_order for atom in coords if atom[0] == el]

    lines = [
        f"Strontium titanate bilayer {short}",
        "1.0",
        f"  {a:.10f}  0.0000000000  0.0000000000",
        f"  0.0000000000  {a:.10f}  0.0000000000",
        f"  0.0000000000  0.0000000000  {c:.10f}",
        "Sr Ti O",
        "2 2 6",
        "Cartesian",
    ]
    for _, x, y, z in grouped:
        lines.append(f"  {x: .10f}  {y: .10f}  {z: .10f}")
    return "\n".join(lines) + "\n"


