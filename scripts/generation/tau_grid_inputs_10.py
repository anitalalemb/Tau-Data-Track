top_idx = {1, 3, 5, 7, 9}

root = Path(".").resolve()


def wrap_xy(x, y):
    return x % a, y % a


def shifted_atoms(i, j):
    sx = i * step
    sy = j * step
    out = []
    for idx, (el, x, y, z) in enumerate(atoms):
        if idx in top_idx:
            x += sx
            y += sy
        x, y = wrap_xy(x, y)
        out.append((el, x, y, z))
    return out


def atomic_positions_block(coords):
    return "\n".join(f"{el:<2} {x: .10f} {y: .10f} {z: .10f}" for el, x, y, z in coords)


def atoms_frac_block(coords):
    lines = []
    for el, x, y, z in coords:
        lines.append(
            f"{el:<2} {x/a: .10f} {y/a: .10f} {z/c: .10f}"
        )
    return "\n".join(lines)


