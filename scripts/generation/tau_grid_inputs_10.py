summary_lines = ["label,i,j,shift_x_A,shift_y_A"]

for i in range(n):
    for j in range(n):
        label = f"sto_bi_tau{i}{j}"
        short = f"tau{i}{j}"
        folder = root / short
        folder.mkdir(parents=True, exist_ok=True)

        coords = shifted_atoms(i, j)

        (folder / f"{label}.scf.in").write_text(make_scf_text(label, coords))
        (folder / f"{label}.nscf.in").write_text(make_nscf_text(label, coords))
        (folder / f"POSCAR_{short}.vasp").write_text(make_poscar_text(short, coords))
        (folder / f"{label}.win").write_text(make_win_text(label, coords))
        (folder / f"pw2wan_{short}.in").write_text(make_pw2wan_text(label))

        sx = i * step
        sy = j * step
        summary_lines.append(f"{short},{i},{j},{sx:.10f},{sy:.10f}")

(root / "tau_shifts_10x10.csv").write_text("\n".join(summary_lines) + "\n")

print("Done. Created tau00 ... tau99 folders with SCF/NSCF/POSCAR/WIN/PW2WAN files.")
